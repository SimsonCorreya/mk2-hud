const compactSvg = (W: number, list: AgentRun[], planned: Planned[], t: ReturnType<typeof totals>): string => {
  const icons = [
    ...list.filter(a => a.status === 'running').map(a => ({ k: costumeOf(a.type), c: colorOf(tierOf(a.type)), s: 'running', dim: false })),
    ...list.filter(a => a.status !== 'running').map(a => ({ k: costumeOf(a.type), c: colorOf(tierOf(a.type)), s: a.status, dim: false })),
    ...planned.map(p => ({ k: p.tier in TIER_COLOR ? p.tier : 'other', c: colorOf(p.tier), s: 'planned', dim: true })),
  ]
  const fit = Math.max(1, Math.floor((W - 150) / 36))
  const shown = icons.slice(0, fit)
  const more = icons.length - shown.length
  const body = shown
    .map((ic, i) => crab(i * 36, 0, ic.k, ic.dim, ic.s === 'running') + (ic.s === 'running' ? `<circle class="live" cx="${i * 36 + 32}" cy="4" r="3" fill="${ic.c}"/>` : ''))
    .join('')
  const x = shown.length * 36 + (more ? 4 : 0)
  return svg(
    W,
    32,
    `${body}${more ? `<text class="s" x="${x}" y="21" font-family="${FONT}" font-size="12">+${more}</text>` : ''}
<text class="s" x="${W}" y="21" text-anchor="end" font-family="${FONT}" font-size="12" font-variant-numeric="tabular-nums">≈${fmtCost(t.cost)} · ${fmtTokens(t.tokens)} · ${fmtTime(t.time)}</text>`,
  )
}

// --- terminal drawing: the same rows in text.

const ctxBar = (pct: number, width: number): string => {
  const filled = Math.round((width * pct) / 100)
  return '█'.repeat(filled) + '░'.repeat(Math.max(0, width - filled))
}

const STATUS_GLYPH: Record<string, string> = { running: '●', done: '✓', failed: '✗', planned: '◷' }

// Opens the agents pane, or closes it when it is up; true when it ends up open.
export async function togglePane($: EngineInterface): Promise<boolean> {
  const isOpen = (await $.ui.panes()).some(p => p.id === PANE)
  if (isOpen) {
    await $.ui.close({ id: PANE })
    return false
  }
  const at = await $.clock.now()
  await update($, now, () => at)
  await $.ui.open({ id: PANE, title: tr().pane })
  return true
}

async function autoOpen($: EngineInterface, key: string): Promise<void> {
  const p = await read($, panel)
  if (p.autoOpenedFor === key) return
  await update($, panel, prev => ({ ...prev, autoOpenedFor: key }))
  void $.ui.open({ id: PANE, title: tr().pane })
}

// Claude's task list drives the bar unless a reported plan is under way.
async function showTasks($: EngineInterface): Promise<void> {
  const items = await read($, taskList)
  await update($, flow, prev => {
    if (prev && !prev.isFinished && sourceOf(prev) === 'plan') return prev
    return tasksFlow(items) ?? (prev && sourceOf(prev) === 'tasks' ? null : prev)
  })
}

// A subagent's own task list fills its row in the agents panel.
async function showSteps($: EngineInterface, agentId: string, items: readonly TaskItem[]): Promise<void> {
  const current = items.find(t => t.status === 'in_progress')
  await update($, agents, list =>
    list.map(a =>
      a.agentId !== agentId
        ? a
        : {
            ...a,
            stepTotal: items.length,
            stepDone: items.filter(t => t.status === 'completed').length,
            stepNote: (current?.activeForm || current?.subject)?.trim() || undefined,
          },
    ),
  )
}

// Mission's part of `session.start`, after the engine's own: the `progress`
// and `step` tools, and the agents' clocks.
export async function missionSessionStart($: EngineInterface, options: Options): Promise<void> {
    await $.tool.register({
      name: 'progress',
      description:
        'Report progress on multi-step work to the progress bar above the prompt. ' +
        'Call it once the plan is clear (title, total, tasks), again with done as each step finishes, ' +
        'when re-planning (tasks), and once at the end with finished: true. Fields left out keep their previous value.',
      inputSchema: {
        type: 'object',
        properties: {
          title: { type: 'string', description: 'Short name of the overall task, a few words.' },
          total: { type: 'integer', minimum: 0, description: 'Number of planned steps.' },
          done: { type: 'integer', minimum: 0, description: 'Number of steps finished so far.' },
          phase: { type: 'string', enum: [...PHASES], description: 'Optional; left out, the bar counts steps.' },
          finished: { type: 'boolean', description: 'True once the work is done.' },
          tasks: {
            type: 'array',
            description:
              'The planned steps in order, numbered from 1. A step handed to a subagent should be titled as its Agent tool `description`, so the agents panel can match the run to it.',
            items: {
              type: 'object',
              properties: {
                title: { type: 'string', description: 'A few words.' },
                tier: { type: 'string', enum: ['fable', 'heavy', 'careful', 'medium', 'light'], description: 'savvy-flow workers only.' },
                after: { type: 'array', items: { type: 'integer' }, description: 'Numbers of the steps this one waits for.' },
              },
              required: ['title'],
            },
          },
        },
      },
      // In the prompt from the start when Claude is asked to report plans, so no ToolSearch round trip.
      ...(options.planReports === false ? {} : { isDeferred: false }),
    })
    await $.tool.register({
      name: 'step',
      description:
        'For subagents: report progress on your own task to the agents panel. ' +
        'Right after reading the brief, call it with `total` (your plan in 3-8 steps) and `done: 0`; ' +
        'call it again as each step finishes. Cheap and silent: it only draws a bar.',
      inputSchema: {
        type: 'object',
        properties: {
          done: { type: 'integer', minimum: 0, description: 'Steps finished so far.' },
          total: { type: 'integer', minimum: 1, description: 'Steps planned; may change if the plan changes.' },
          note: { type: 'string', description: 'The step in progress, a few words.' },
        },
        required: ['done'],
      },
    })

    // Ticks the running agents' clocks; quiet when nothing runs.
    $.clock.every(1000, () => {
      void (async () => {
        const list = await read($, agents)
        if (!list.some(a => a.status === 'running')) return
        const at = await $.clock.now()
        await update($, now, () => at)
      })()
    })
}

// Mission's part of `turn.step` for a subagent, after the request: its live
// context, tokens and cost.
export async function missionSubagentStep(
  $: EngineInterface,
  e: EventOf['turn.step'],
  result: EventResult<'turn.step'>,
): Promise<void> {
  const agentId = e.agentId
  const usage = result.usage
  if (!agentId || !usage) return

  const model = usage.model || e.model
  await update($, agents, list =>
    list.map((a): AgentRun =>
      a.agentId !== agentId
        ? a
        : {
            ...a,
            model,
            effort: typeof e.effort === 'string' ? e.effort : a.effort,
            status: 'running',
            endedAt: undefined,
            contextTokens:
              (usage.input_tokens || 0) +
              (usage.cache_read_input_tokens || 0) +
              (usage.cache_creation_input_tokens || 0) +
              (usage.output_tokens || 0),
            contextMax: windowOf(model),
            tokens:
              a.tokens +
              (usage.input_tokens || 0) +
              (usage.output_tokens || 0) +
              (usage.cache_read_input_tokens || 0) +
              (usage.cache_creation_input_tokens || 0),
            costUsd: a.costUsd + costOf(model, usage),
            steps: a.steps + 1,
          },
    ),
  )
}

// Mission's part of `turn.complete` for a subagent, before the engine's own:
// the run is done or failed.
export async function missionTurnComplete($: EngineInterface, e: EventOf['turn.complete']): Promise<void> {
  const agentId = e.agentId
  if (!agentId) return
  const at = await $.clock.now()
  await update($, agents, list =>
    list.map((a): AgentRun => {
      if (a.agentId !== agentId) return a
      // A run whose steps went unseen still gets the turn's own sum.
      const fallback = a.steps === 0 && e.usage
      return {
        ...a,
        status: e.reason === 'answer' ? 'done' : 'failed',
        endedAt: at,
        ...(fallback && e.usage
          ? {
              model: e.usage.model || a.model,
              tokens:
                e.usage.input_tokens +
                e.usage.output_tokens +
                e.usage.cache_read_input_tokens +
                e.usage.cache_creation_input_tokens,
              costUsd: costOf(e.usage.model || a.model, e.usage),
            }
          : {}),
      }
    }),
  )
  await update($, now, () => at)
}

export function registerMission(on: On, options: Options): void {
  // Asks the main conversation to report its multi-step work, unless it keeps a
  // task list the bar already follows.
  on('prompt.compose', async ($, e, next) => {
    const composed = await next(e)
    const hasTaskList = e.tools.some(t => TASK_TOOLS.includes(t))
    if (options.planReports === false || hasTaskList || !e.tools.includes(TOOL)) return composed
    return {
      sections: [...composed.sections, { id: 'mk2-hud:plans', text: PLAN_PROMPT, scope: 'session' as const }],
    }
  })

  // A finished bar steps aside when the next request starts.
  on('prompt.submit', async ($, e, next) => {
    if (isPingText(e.text)) return next(e)
    const f = await read($, flow)
    if (f && viewOf(f, await read($, agents)).isFinished) {
      await update($, flow, () => null)
      if (sourceOf(f) === 'tasks') await update($, taskList, () => [])
    }
    return next(e)
  }).catch(($, e, next) => next(e))

  on('tool.call', { tool: TOOL }, async ($, e) => {
    if (e.agentId) return { result: 'ignored: the bar follows the main conversation; subagents report with step' }
    const input = e as unknown as ProgressInput
    const prev = await read($, flow)
    if (isNewFlow(prev, input) && input.title !== undefined) {
      // A new flow starts with a clean list; agents still running stay.
      await update($, agents, list => list.filter(a => a.status === 'running'))
    }
    const next = await update($, flow, p => merge(p, input))
    // Only a savvy-flow plan (one naming worker tiers) opens the agents panel by itself.
    if (next && next.tasks.some(t => t.tier in TIER_MODEL)) await autoOpen($, next.title)
    return { result: `ok: ${label(next ?? blank())}` }
  })

  // Claude's own task list, whole (TodoWrite) or one task at a time (TaskCreate, TaskUpdate).
  on('tool.call', { tool: 'TodoWrite' }, async ($, e, next) => {
    const answer = await next(e)
    if (e.tool !== 'TodoWrite' || answer.isError || answer.result === undefined) return answer
    const items: TaskItem[] = (e.todos ?? []).map((t, i) => ({
      id: String(i + 1),
      subject: t.content,
      activeForm: t.activeForm,
      status: t.status,
    }))
    if (e.agentId) {
      await showSteps($, e.agentId, items)
    } else {
      await update($, taskList, () => items)
      await showTasks($)
    }
    return answer
  }).catch(($, e, next) => next(e))

  on('tool.call', { tool: 'TaskCreate' }, async ($, e, next) => {
    const answer = await next(e)
    if (e.tool !== 'TaskCreate' || e.agentId || answer.isError || answer.result === undefined) return answer
    const id = (answer.result as { task?: { id?: string } }).task?.id
    if (!id) return answer
    const item: TaskItem = { id, subject: e.subject, activeForm: e.activeForm, status: 'pending' }
    await update($, taskList, items => {
      // A list that was all done starts over with the new task.
      const kept = items.length > 0 && items.every(t => t.status === 'completed') ? [] : items
      return [...kept.filter(t => t.id !== id), item]
    })
    await showTasks($)
    return answer
  }).catch(($, e, next) => next(e))

  on('tool.call', { tool: 'TaskUpdate' }, async ($, e, next) => {
    const answer = await next(e)
    if (e.tool !== 'TaskUpdate' || answer.isError || answer.result === undefined) return answer
    if ((answer.result as { success?: boolean }).success === false) return answer
    const { taskId, status, subject, activeForm } = e
    const agentId = e.agentId
    await update($, taskList, items => {
      if (status === 'deleted') return items.filter(t => t.id !== taskId)
      const known = items.find(t => t.id === taskId)
      if (known) {
        return items.map(t =>
          t.id !== taskId
            ? t
            : { ...t, subject: subject ?? t.subject, activeForm: activeForm ?? t.activeForm, status: status ?? t.status },
        )
      }
      // A task created before this mod loaded joins the list; a subagent's own does not.
      return agentId ? items : [...items, { id: taskId, subject: subject ?? `#${taskId}`, activeForm, status: status ?? 'pending' }]
    })
    await showTasks($)
    return answer
  }).catch(($, e, next) => next(e))

  // A worker's own progress: the call runs in the worker's loop, so agentId names it.
  on('tool.call', { tool: STEP_TOOL }, async ($, e) => {
    const input = e as unknown as { done?: number; total?: number; note?: string }
    const agentId = e.agentId
    if (!agentId) return { result: 'ignored: only subagents report steps' }
    await update($, agents, list =>
      list.map(a => {
        if (a.agentId !== agentId) return a
        const total = Math.max(0, Math.round(input.total ?? a.stepTotal ?? 0))
        const done = Math.max(0, Math.round(input.done ?? a.stepDone ?? 0))
        return { ...a, stepTotal: total, stepDone: total ? Math.min(total, done) : done, stepNote: input.note?.trim() || undefined }
      }),
    )
    return { result: 'ok' }
  })

  // Safety net: worker launches move the faint layer even if the orchestrator forgets to report.
  on('tool.call', { tool: 'Agent' }, async ($, e, next) => {
    const type = String(e.subagent_type ?? '')
    if (!type.startsWith('savvy-')) return next(e)

    await update($, flow, prev => {
      const base = prev && !prev.isFinished ? { ...blank(), ...prev } : blank()
      return { ...base, running: base.running + 1, phase: base.phase === 'plan' ? 'delegate' : base.phase }
    })
    try {
      return await next(e)
    } finally {
      await update($, flow, prev => (prev ? { ...prev, running: Math.max(0, prev.running - 1) } : prev))
    }
  })

  on('agent.spawn', async ($, e, next) => {
    const started = await next(e)
    if (started.deny !== undefined) return started

    const at = await $.clock.now()
    await update($, agents, list => {
      const round = 1 + list.filter(a => norm(a.description) === norm(e.description) && e.description).length
      const run: AgentRun = {
        id: started.agentId ?? e.tool_use_id,
        agentId: started.agentId,
        type: e.subagentType,
        description: e.description,
        model: started.model,
        status: 'running',
        startedAt: at,
        contextTokens: 0,
        contextMax: windowOf(started.model),
        tokens: 0,
        costUsd: 0,
        steps: 0,
        round,
      }
      return [...list.filter(a => a.id !== run.id), run].slice(-200)
    })
    await update($, now, () => at)
    // With no plan or task list under way, the subagents get a bar of their own.
    await update($, flow, prev =>
      prev && !prev.isFinished ? prev : { ...blank(), source: 'agents' as const, phase: 'delegate' as const, startedAt: at },
    )
    if (e.subagentType.startsWith('savvy-')) {
      const f = await read($, flow)
      await autoOpen($, f && !f.isFinished ? f.title : 'savvy-flow')
    }
    return started
  })

  on('ui.render', { component: 'Pane', requestId: PANE }, async ($, e) => {
    const s = tr()
    const ui = $.ui.resolve(e)
    const { Box, Text, Button } = ui
    const list = await read($, agents)
    const stored = await read($, flow)
    const f = stored && viewOf(stored, list)
    const p: Panel = await read($, panel)
    const at = Math.max(await read($, now), ...list.map(a => a.startedAt), 0)

    const running = list.filter(a => a.status === 'running').reverse()
    const finished = list.filter(a => a.status !== 'running').reverse()
    const planned = plannedOf(f, list)
    const t = totals(list, at)
    // The pane's title says "Agents"; inside, only the flow's own name.
    const title = f && !f.isFinished && sourceOf(f) !== 'agents' ? f.title : ''

    const toggleCompact = (
      <Button
        key="compact"
        label={p.isCompact ? s.expand : s.collapse}
        plain
        onPress={() => update($, panel, prev => ({ ...prev, isCompact: !prev.isCompact }))}
      />
    )
    const toggleDone = (
      <Button
        key="done"
        label={`${p.isDoneCollapsed ? '▸' : '▾'} ${s.finished} · ${finished.length}`}
        plain
        onPress={() => update($, panel, prev => ({ ...prev, isDoneCollapsed: !prev.isDoneCollapsed }))}
      />
    )
    const isEmpty = list.length === 0 && planned.length === 0
    const summary = `≈${fmtCost(t.cost)}, ${fmtTokens(t.tokens)} ${s.tokensWord}, ${fmtTime(t.time)}`

    if (e.surface === 'desktop' && 'Svg' in ui) {
      const { Svg } = ui
      const W = Math.max(240, Math.min(900, (e.props.bodyColumns || 40) * 8 - 8))
      const section = (key: string, text: string) => (
        <Text key={key} dimColor>
          {text}
        </Text>
      )

      if (p.isCompact) {
        return (
          <Box flexDirection="column" gap={1}>
            <Svg source={compactSvg(W, list, planned, t)} alt={`${list.length} ${s.agentsCount}, ${summary}`} width={W} height={32} />
            {toggleCompact}
          </Box>
        )
      }
      return (
        <Box flexDirection="column">
          <Svg source={headerSvg(W, title, t)} alt={title ? `${title}: ${summary}` : summary} width={W} height={headerHeight(title)} />
          {toggleCompact}
          {isEmpty && <Text dimColor>{s.empty}</Text>}
          {running.length > 0 && section('h-run', `${s.running} · ${running.length}`)}
          {running.map(a => (
            <Svg key={a.id} source={agentSvg(W, a, at)} alt={`${a.description}: ${modelName(a.model)}, ${s.isRunning}`} width={W} height={66} />
          ))}
          {finished.length > 0 && toggleDone}
          {!p.isDoneCollapsed &&
            finished.map(a => (
              <Svg key={a.id} source={agentSvg(W, a, at)} alt={`${a.description}: ${modelName(a.model)}, ${s.isFinished}`} width={W} height={66} />
            ))}
          {planned.length > 0 && section('h-plan', `${s.planned} · ${planned.length}`)}
          {planned.map(pl => (
            <Svg key={`plan-${pl.n}`} source={plannedSvg(W, pl)} alt={`${pl.n}. ${pl.title}: ${s.isPlanned}`} width={W} height={46} />
          ))}
        </Box>
      )
    }

    // Terminal: the same content in text rows.
    const cols = Math.max(24, e.props.bodyColumns || 40)
    const barW = Math.max(6, Math.min(20, cols - 34))
    const row = (a: AgentRun) => {
      const tier = tierOf(a.type)
      const color = colorOf(tier)
      const ctx = ctxOf(a)
      const progress = progressOf(a)
      const model = a.effort ? `${modelName(a.model)} · ${a.effort}` : modelName(a.model)
      const steps = a.stepTotal ? `${a.stepDone ?? 0}/${a.stepTotal}${a.stepNote ? ' ' + a.stepNote : ''} · ` : ''
      return (
        <Box key={a.id} flexDirection="column" marginBottom={1}>
          <Box flexDirection="row" gap={1}>
            <Text color={color}>▣</Text>
            <Text bold wrap="truncate-end">
              {a.description || a.type}
            </Text>
            <Text color={a.status === 'failed' ? 'red' : a.status === 'done' ? 'green' : color}>{STATUS_GLYPH[a.status]}</Text>
          </Box>
          <Text dimColor wrap="truncate-end">
            {'  '}
            {tier === 'other' ? a.type : tier} · {model}
            {a.round > 1 ? ` · ${s.round} ${a.round}` : ''}
          </Text>
          <Text wrap="truncate-end">
            {'  '}
            {progress === null ? <Text dimColor>{ctxBar(ctx, barW)}</Text> : <Text color={color}>{ctxBar(progress * 100, barW)}</Text>}
            <Text dimColor>
              {' '}
              {steps}ctx {ctx}% · {fmtTokens(a.contextTokens)} ≈{fmtCost(a.costUsd)} {fmtTime(elapsed(a, at))}
            </Text>
          </Text>
        </Box>
      )
    }

    return (
      <Box flexDirection="column">
        <Box flexDirection="row" justifyContent="space-between">
          <Text bold wrap="truncate-end">
            {title}
          </Text>
          {toggleCompact}
        </Box>
        <Text dimColor>
          ≈{fmtCost(t.cost)} · {fmtTokens(t.tokens)} {s.tokensWord} · {fmtTime(t.time)}
        </Text>
        {p.isCompact ? (
          <Text wrap="truncate-end">
            {[...running, ...finished].map(a => (
              <Text key={a.id} color={colorOf(tierOf(a.type))}>
                {STATUS_GLYPH[a.status]}{' '}
              </Text>
            ))}
            {planned.map(pl => (
              <Text key={`plan-${pl.n}`} dimColor>
                ◷{' '}
              </Text>
            ))}
          </Text>
        ) : (
          <Box flexDirection="column" marginTop={1}>
            {isEmpty && <Text dimColor>{s.empty}</Text>}
            {running.length > 0 && <Text dimColor>{s.running} · {running.length}</Text>}
            {running.map(row)}
            {finished.length > 0 && toggleDone}
            {!p.isDoneCollapsed && finished.map(row)}
            {planned.length > 0 && <Text dimColor>{s.planned} · {planned.length}</Text>}
            {planned.map(pl => {
              const tier = pl.tier in TIER_COLOR ? pl.tier : 'other'
              return (
                <Box key={`plan-${pl.n}`} flexDirection="column" marginBottom={1}>
                  <Text dimColor wrap="truncate-end">
                    <Text color={colorOf(tier)}>▢</Text> {pl.n}. {pl.title} ◷
                  </Text>
                  <Text dimColor wrap="truncate-end">
                    {'  '}
                    {tier} · {TIER_MODEL[tier] ?? ''}
                    {pl.after.length ? ` · ${s.after} ${pl.after.join(', ')}` : ''}
                  </Text>
                </Box>
              )
            })}
          </Box>
        )}
      </Box>
    )
  })
}
