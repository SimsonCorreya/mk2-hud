export const sourceOf = (f: Flow): NonNullable<Flow['source']> => f.source ?? 'plan'

// A reported plan takes over from a task list or a crew of subagents.
const isNewFlow = (prev: Flow | null, input: ProgressInput): boolean =>
  !prev ||
  prev.isFinished ||
  sourceOf(prev) !== 'plan' ||
  (input.title !== undefined && input.title.trim() !== prev.title)

const cleanTasks = (tasks: ProgressInput['tasks']): PlannedTask[] | undefined =>
  tasks
    ?.filter(t => t.title?.trim())
    .map(t => ({
      title: (t.title ?? '').trim(),
      tier: (t.tier ?? '').replace(/^savvy-/, '').trim().toLowerCase(),
      after: (t.after ?? []).filter(n => Number.isInteger(n) && n > 0),
    }))

const merge = (prev: Flow | null, input: ProgressInput): Flow => {
  // A new title means a new flow: never carry counters over from an earlier one.
  const base = isNewFlow(prev, input) || !prev ? blank() : { ...blank(), ...prev }
  const tasks = cleanTasks(input.tasks) ?? base.tasks
  const total = Math.max(0, Math.round(input.total ?? (input.tasks ? tasks.length : base.total)))
  const done = Math.min(total || Infinity, Math.max(0, Math.round(input.done ?? base.done)))
  // A plan reported with no phase is under way once it has steps to count.
  const fallback = base.phase === 'plan' && total > 0 ? 'delegate' : base.phase
  const phase = input.phase && PHASES.includes(input.phase) ? input.phase : fallback
  return {
    ...base,
    title: input.title?.trim() || base.title,
    total,
    done,
    phase: input.finished ? 'close' : phase,
    isFinished: input.finished === true,
    tasks,
    source: 'plan',
  }
}

// The bar for Claude's own task list: the step in progress names it.
const tasksFlow = (items: readonly TaskItem[]): Flow | null => {
  if (items.length === 0) return null
  const done = items.filter(t => t.status === 'completed').length
  const current = items.find(t => t.status === 'in_progress')
  const upcoming = items.find(t => t.status === 'pending')
  const isFinished = done === items.length
  return {
    ...blank(),
    title: (current ? current.activeForm || current.subject : upcoming?.subject)?.trim() || tr().tasks,
    total: items.length,
    done,
    phase: isFinished ? 'close' : 'delegate',
    isFinished,
    source: 'tasks',
  }
}

// An `agents` flow is counted from the runs, so background agents that finish
// after their Agent call returned are counted too.
export const viewOf = (f: Flow, list: readonly AgentRun[]): Flow => {
  if (sourceOf(f) !== 'agents') return f
  const runs = list.filter(a => a.startedAt >= (f.startedAt ?? 0))
  const running = runs.filter(a => a.status === 'running').length
  const only = runs.length === 1 ? runs[0] : undefined
  return {
    ...f,
    title: only?.description?.trim() || tr().subagents,
    total: runs.length,
    done: runs.length - running,
    running,
    isFinished: runs.length > 0 && running === 0,
  }
}

export const label = (f: Flow): string => {
  const s = tr()
  if (f.isFinished) return s.done
  if (sourceOf(f) === 'agents') return `${s.agents} ${f.done}/${f.total}`
  if (f.phase === 'plan') return s.plan
  if (f.phase === 'design') return s.design
  const count = f.total ? `${f.done}/${f.total}` : `${f.running} ${s.busy}`
  return `${f.phase === 'review' ? s.review : s.tasks} ${count}`
}

